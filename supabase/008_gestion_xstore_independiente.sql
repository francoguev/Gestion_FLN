create extension if not exists pgcrypto;

create table if not exists public.xstore_cash_closures (
  id uuid primary key default gen_random_uuid(),
  pdv text not null,
  cash_date date not null,
  cash_amount numeric(12,2) not null default 0 check (cash_amount >= 0),
  store_closed boolean not null default false,
  store_closed_reason text,
  evidence_path text,
  status text not null default 'pending_deposit' check (status in ('pending_deposit','deposit_review','validated','payjoy_validated','difference','observed','store_closed')),
  payjoy_amount numeric(12,2) not null default 0 check (payjoy_amount >= 0),
  registered_by_email text not null,
  updated_by_email text not null,
  review_started_at timestamptz,
  review_started_by_email text,
  validated_at timestamptz,
  validated_by_email text,
  review_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint xstore_cash_closures_pdv_date_key unique (pdv, cash_date)
);

alter table public.xstore_cash_closures add column if not exists store_closed boolean not null default false;
alter table public.xstore_cash_closures add column if not exists store_closed_reason text;
-- Compatibilidad con pruebas del prototipo anterior: "no_cash" pasa a ser cierre de tienda.
update public.xstore_cash_closures set status='store_closed', store_closed=true
where status='no_cash';
alter table public.xstore_cash_closures drop constraint if exists xstore_cash_closures_status_check;
alter table public.xstore_cash_closures add constraint xstore_cash_closures_status_check
  check (status in ('pending_deposit','deposit_review','validated','payjoy_validated','difference','observed','store_closed'));

create table if not exists public.xstore_deposits (
  id uuid primary key default gen_random_uuid(),
  pdv text not null,
  deposit_date date not null,
  deposit_amount numeric(12,2) not null check (deposit_amount > 0),
  evidence_path text not null,
  registered_by_email text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.xstore_deposit_allocations (
  id uuid primary key default gen_random_uuid(),
  deposit_id uuid not null references public.xstore_deposits(id) on delete cascade,
  closure_id uuid not null references public.xstore_cash_closures(id) on delete cascade,
  allocated_amount numeric(12,2) not null check (allocated_amount > 0),
  created_at timestamptz not null default now(),
  constraint xstore_deposit_allocations_unique unique (deposit_id, closure_id)
);

create table if not exists public.xstore_audit_log (
  id bigint generated by default as identity primary key,
  closure_id uuid references public.xstore_cash_closures(id) on delete cascade,
  action text not null,
  actor_email text not null,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists xstore_cash_closures_pdv_date_idx on public.xstore_cash_closures(pdv, cash_date desc);
create index if not exists xstore_deposits_pdv_date_idx on public.xstore_deposits(pdv, deposit_date desc);
create index if not exists xstore_allocations_closure_idx on public.xstore_deposit_allocations(closure_id);

-- Autorización: siempre se evalúa en la base; el navegador nunca decide permisos.
create or replace function public.xstore_current_email()
returns text language sql stable security definer set search_path = public as $$
  select lower(coalesce(auth.jwt()->>'email',''));
$$;

create or replace function public.xstore_current_cargo()
returns text language sql stable security definer set search_path = public as $$
  select lower(trim(coalesce(cargo,''))) from public.profiles
  where lower(email) = public.xstore_current_email() limit 1;
$$;

create or replace function public.xstore_current_pdv()
returns text language sql stable security definer set search_path = public as $$
  select pdv from public.profiles where lower(email) = public.xstore_current_email() limit 1;
$$;

create or replace function public.xstore_pdv_key(p_value text)
returns text language sql immutable as $$
  select trim(both '_' from regexp_replace(lower(translate(coalesce(p_value,''),'ÁÉÍÓÚÜÑáéíóúüñ','AEIOUUNaeiouun')),'[^a-z0-9]+','_','g'));
$$;

-- Re-declare after legacy normalization to make this migration robust when read
-- under Windows code pages; Unicode escapes preserve accented PDV names.
create or replace function public.xstore_pdv_key(p_value text)
returns text language sql immutable as $$
  select trim(both '_' from regexp_replace(
    replace(replace(replace(replace(replace(replace(replace(
      lower(coalesce(p_value,'')),
      U&'\00E1','a'), U&'\00E9','e'), U&'\00ED','i'), U&'\00F3','o'),
      U&'\00FA','u'), U&'\00FC','u'), U&'\00F1','n'),
    '[^a-z0-9]+','_','g'
  ));
$$;

create or replace function public.xstore_can_access_pdv(p_pdv text)
returns boolean language sql stable security definer set search_path = public as $$
  -- Un usuario autenticado sin perfil no obtiene acceso por defecto.
  -- Asesor: solamente su propio PDV. Los cargos de gestiÃ³n ven PDV existentes.
  select case
    when not exists (select 1 from public.profiles p where lower(p.email) = public.xstore_current_email()) then false
    when public.xstore_current_cargo() = 'asesor'
      then lower(trim(coalesce(public.xstore_current_pdv(),''))) = lower(trim(coalesce(p_pdv,'')))
    when public.xstore_current_cargo() in ('supervisor','operaciones','gerente','gerencia')
      then exists(select 1 from public.profiles p where lower(trim(coalesce(p.pdv,''))) = lower(trim(coalesce(p_pdv,''))))
    else false
  end;
$$;

create or replace function public.xstore_is_operations()
returns boolean language sql stable security definer set search_path = public as $$
  select public.xstore_current_cargo() = 'operaciones';
$$;

create or replace function public.xstore_can_upload_path(p_name text)
returns boolean language sql stable security definer set search_path = public as $$
  select exists(
    select 1 from public.profiles p
    where public.xstore_pdv_key(p.pdv) = split_part(p_name,'/',2)
      and public.xstore_can_access_pdv(p.pdv)
  );
$$;

create or replace function public.xstore_add_audit(p_closure_id uuid, p_action text, p_detail jsonb default '{}'::jsonb)
returns void language plpgsql security definer set search_path = public as $$
begin
  insert into public.xstore_audit_log(closure_id,action,actor_email,detail)
  values(p_closure_id,p_action,public.xstore_current_email(),coalesce(p_detail,'{}'::jsonb));
end;
$$;

