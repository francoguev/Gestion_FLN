create extension if not exists pgcrypto;

create table if not exists public.xstore_cash_closures (
  id uuid primary key default gen_random_uuid(),
  pdv text not null,
  cash_date date not null,
  cash_amount numeric(12,2) not null default 0 check (cash_amount >= 0),
  no_cash boolean not null default false,
  no_cash_reason text,
  evidence_path text,
  status text not null default 'pending_deposit' check (status in (
    'pending_deposit', 'deposit_review', 'validated', 'payjoy_validated',
    'difference', 'observed', 'no_cash'
  )),
  payjoy_amount numeric(12,2) not null default 0 check (payjoy_amount >= 0),
  registered_by_email text not null,
  updated_by_email text not null,
  review_started_at timestamptz,
  review_started_by_email text,
  validated_at timestamptz,
  validated_by_email text,
  review_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint xstore_cash_closures_pdv_date_key unique (pdv, cash_date),
  constraint xstore_cash_closures_no_cash_check check (
    (no_cash = false) or (cash_amount = 0)
  ),
  constraint xstore_cash_closures_payjoy_check check (payjoy_amount <= cash_amount)
);

create table if not exists public.xstore_deposits (
  id uuid primary key default gen_random_uuid(),
  pdv text not null,
  deposit_date date not null,
  deposit_amount numeric(12,2) not null check (deposit_amount > 0),
  evidence_path text not null,
  registered_by_email text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.xstore_deposit_allocations (
  id uuid primary key default gen_random_uuid(),
  deposit_id uuid not null references public.xstore_deposits(id) on delete cascade,
  closure_id uuid not null references public.xstore_cash_closures(id) on delete cascade,
  allocated_amount numeric(12,2) not null check (allocated_amount > 0),
  created_at timestamptz not null default now(),
  constraint xstore_deposit_allocations_unique unique (deposit_id, closure_id)
);

create table if not exists public.xstore_audit_log (
  id bigint generated by default as identity primary key,
  closure_id uuid references public.xstore_cash_closures(id) on delete cascade,
  action text not null,
  actor_email text not null,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists xstore_cash_closures_pdv_date_idx on public.xstore_cash_closures (pdv, cash_date desc);
create index if not exists xstore_deposits_pdv_date_idx on public.xstore_deposits (pdv, deposit_date desc);
create index if not exists xstore_deposit_allocations_closure_idx on public.xstore_deposit_allocations (closure_id);

-- Funciones privadas de autorización. El navegador nunca decide permisos.
create or replace function public.xstore_current_email()
returns text language sql stable security definer set search_path = public as $$
  select lower(coalesce(auth.jwt() ->> 'email', ''));
$$;

create or replace function public.xstore_current_cargo()
returns text language sql stable security definer set search_path = public as $$
  select lower(trim(coalesce(cargo, '')))
  from public.profiles
  where lower(email) = public.xstore_current_email()
  limit 1;
$$;

create or replace function public.xstore_current_pdv()
returns text language sql stable security definer set search_path = public as $$
  select pdv
  from public.profiles
  where lower(email) = public.xstore_current_email()
  limit 1;
$$;

create or replace function public.xstore_is_operations()
returns boolean language sql stable security definer set search_path = public as $$
  select public.xstore_current_cargo() = 'operaciones';
$$;

create or replace function public.xstore_can_access_pdv(p_pdv text)
returns boolean language sql stable security definer set search_path = public as $$
  select case
    when public.xstore_current_cargo() = 'asesor'
      then lower(trim(coalesce(public.xstore_current_pdv(), ''))) = lower(trim(coalesce(p_pdv, '')))
    else public.xstore_current_cargo() in ('operaciones', 'supervisor', 'gerente')
  end;
$$;

create or replace function public.xstore_can_upload_path(p_name text)
returns boolean language sql stable security definer set search_path = public as $$
  select public.xstore_can_access_pdv(replace(split_part(p_name, '/', 2), '_', ' '));
$$;

